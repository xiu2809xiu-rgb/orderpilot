// Renders the web image's nginx configuration:
//
//   node scripts/render-nginx.mjs <outDir>
//
// writes <outDir>/default.conf (the server) and <outDir>/security-headers.conf
// (the response headers of every static file). The headers come from
// security-headers.ts, the same module `vite preview` uses, so the dev preview
// and the image cannot drift apart. VITE_SENTRY_DSN decides whether the Sentry
// origin is allowed, exactly as it decides whether Sentry is in the bundle.
//
// Node strips the types of security-headers.ts itself.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const TEMPLATE = resolve(HERE, "../nginx/default.conf.template");

/** host:port, nothing that could end a config line. */
const UPSTREAM = /^[a-z0-9][a-z0-9.-]*:\d{1,5}$/i;

/**
 * @param {{ apiUpstream?: string, headers: Record<string, string>, template?: string }} options
 * @returns {{ serverConf: string, headersConf: string }}
 */
export function renderNginx({
  apiUpstream = "api:3000",
  headers,
  template = readFileSync(TEMPLATE, "utf8"),
}) {
  if (!UPSTREAM.test(apiUpstream)) {
    throw new Error(
      `API upstream must look like host:port, got "${apiUpstream}"`,
    );
  }
  const lines = Object.entries(headers).map(([name, value]) => {
    // These values go inside nginx double quotes.
    if (/["\\$;\n]/.test(value.replaceAll("; ", ""))) {
      throw new Error(`Header ${name} has a character nginx would misread`);
    }
    return `add_header ${name} "${value}" always;`;
  });
  return {
    serverConf: template.replaceAll("__API_UPSTREAM__", apiUpstream),
    headersConf: `# Generated by scripts/render-nginx.mjs. Do not edit.\n${lines.join("\n")}\n`,
  };
}

async function main() {
  const outDir = process.argv[2];
  if (outDir === undefined) {
    console.error("Usage: node scripts/render-nginx.mjs <outDir>");
    return 1;
  }
  const { securityHeaders } = await import(
    pathToFileURL(resolve(HERE, "../security-headers.ts")).href
  );
  const sentryDsn = process.env["VITE_SENTRY_DSN"] || undefined;
  const { serverConf, headersConf } = renderNginx({
    apiUpstream: process.env["API_UPSTREAM"] || undefined,
    headers: securityHeaders(sentryDsn),
  });
  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, "default.conf"), serverConf);
  writeFileSync(join(outDir, "security-headers.conf"), headersConf);
  return 0;
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? "").href) {
  process.exitCode = await main();
}
